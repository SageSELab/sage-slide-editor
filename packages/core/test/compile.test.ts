import { execFile } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { promisify } from 'node:util';
import { describe, expect, it } from 'vitest';
import { compileTalk, ENGINE_FILES, renderIndex } from '../src/compile.ts';
import { ISSTA, oneChapter, REPO } from './helpers.ts';

describe('compile', () => {
  it('matches spikes/format/build.mjs byte-for-byte except the generator comment', async () => {
    const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'talkc-c-'));
    try {
      const snap = path.join(tmp, 'issta26');
      fs.cpSync(ISSTA, snap, { recursive: true, filter: (s) => !s.startsWith(path.join(ISSTA, 'build')) });
      const r = compileTalk(snap, { outDir: path.join(tmp, 'out') });
      expect(r.ok).toBe(true);
      await promisify(execFile)(process.execPath, [path.join(REPO, 'spikes/format/build.mjs'), snap]);
      const strip = (s: string) => s.replace(/<!-- generated by .*? -->/, '');
      expect(strip(fs.readFileSync(r.outFile!, 'utf8'))).toBe(strip(fs.readFileSync(path.join(snap, 'build/index.html'), 'utf8')));
      for (const f of ENGINE_FILES) expect(fs.existsSync(path.join(tmp, 'out', f))).toBe(true);
      expect(fs.existsSync(path.join(tmp, 'out/assets'))).toBe(true);
    } finally { fs.rmSync(tmp, { recursive: true, force: true }); }
  }, 60_000);

  it('emits each script with a sourceURL, the spine with < escaped, and boots', () => {
    const t = oneChapter([['a', "B.in('#h', 0); // </script>"]], '<div class="scene"><h1 id="h">x</h1></div>');
    (t.raw as { title: string }).title = 'A <b> & c';
    t.spine!.title = 'A <b> & c';
    const { html } = renderIndex(t, 'mini');
    expect(html).toContain('//# sourceURL=beats/c.js');
    expect(html).toContain('<title>A &lt;b> &amp; c</title>');
    expect(html).toContain('"title":"A \\u003cb> & c"');
    expect(html!.trimEnd().endsWith('<script>Talk.boot();</script>\n</body>\n</html>')).toBe(true);
  });

  it('fails on a script syntax error instead of shipping a blank stage', () => {
    const t = oneChapter([['a', 'B.in(#h, 0);']], '<div></div>');
    const r = renderIndex(t);
    expect(r.html).toBeNull();
    expect(r.diagnostics).toMatchObject([{ code: 'script-syntax', file: 'beats/c.js', line: 2 }]);
  });

  it('fails when the talk has load errors', () => {
    const t = oneChapter([['a', '']], '');
    t.diagnostics.push({ code: 'file-missing', severity: 'error', message: 'x' });
    expect(renderIndex(t).html).toBeNull();
  });
});
