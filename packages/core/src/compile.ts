// compile.ts — talk folder -> build/index.html (productized spikes/format/build.mjs).
//
// Shape (PLAN 4): layers then each chapter's scene inside .film/.stage, verbatim (not
// re-indented: a line inside a white-space:pre code pane is content); theme inlined; the
// spine inlined as JSON (`<` escaped); the engine (talk.js, talk.css, edit.js,
// talk-layout.js) and assets/ copied next to the page so relative font/image paths resolve;
// each lib and motion file its own classic <script> with a sourceURL, syntax-checked first so
// a parse error fails the build instead of blanking the stage; then Talk.boot().
// The output is byte-identical to build.mjs's apart from the generator comment.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { parse as parseJs } from 'acorn';
import { diag, type Diagnostic } from './diagnostics.ts';
import { loadTalk, type LoadedTalk, type SourceFile } from './load.ts';

export const ENGINE_FILES = ['talk.js', 'talk.css', 'edit.js', 'talk-layout.js'] as const;
export const DEFAULT_ENGINE_DIR = fileURLToPath(new URL('../../engine/src/', import.meta.url));

/**
 * The engine folder to use when a caller passes none: `SAGE_ENGINE_DIR` when set (the packaged
 * app's sidecar sets it, since a bundled core no longer sits next to packages/engine), else
 * packages/engine/src. Read at call time, not import time.
 */
export function defaultEngineDir(env: NodeJS.ProcessEnv = process.env): string {
  return env.SAGE_ENGINE_DIR || DEFAULT_ENGINE_DIR;
}

export interface CompileOptions {
  /** Output folder; default `<talk>/build`. */
  outDir?: string;
  /** Folder holding the engine files; default `defaultEngineDir()`. */
  engineDir?: string;
}

export interface CompileResult {
  ok: boolean;
  outFile: string | null;
  bytes: number;
  diagnostics: Diagnostic[];
}

const esc = (s: string) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;');
const trimEnd = (s: string) => s.replace(/\s+$/, '');

/** Syntax-check one classic script; returns a diagnostic on failure. */
export function checkScript(f: SourceFile): Diagnostic | null {
  try { parseJs(f.text, { ecmaVersion: 'latest', sourceType: 'script' }); new Function(f.text); return null; } catch (e) {
    const loc = (e as { loc?: { line: number; column: number } }).loc;
    return diag('script-syntax', 'error', `syntax error: ${(e as Error).message}`, { file: f.path, line: loc?.line, col: loc ? loc.column + 1 : undefined });
  }
}

/** Render build/index.html for a loaded talk (no file system writes). */
export function renderIndex(talk: LoadedTalk, talkName = path.basename(talk.dir || 'talk')): { html: string | null; diagnostics: Diagnostic[] } {
  const D = talk.diagnostics.filter((d) => d.severity === 'error');
  const spine = talk.spine, raw = talk.raw as Record<string, unknown>;
  if (!spine || D.length) return { html: null, diagnostics: D };
  const scenes: string[] = [];
  if (talk.layers) scenes.push(`<!-- ${talk.layers.path} -->\n${talk.layers.text}`);
  const motion: SourceFile[] = [];
  for (const c of talk.chapters) {
    if (c.scene) scenes.push(`<!-- ${c.scene.path} -->\n${c.scene.text}`);
    if (c.motion) motion.push(c.motion);
  }
  const scripts = [...talk.lib, ...motion];
  for (const s of scripts) { const d = checkScript(s); if (d) D.push(d); }
  if (D.length) return { html: null, diagnostics: D };
  const script = (f: SourceFile) => `<script>\n${trimEnd(f.text)}\n//# sourceURL=${f.path}\n</script>`;
  // </script> inside JSON would end the block early; escape '<' defensively.
  const spineJson = JSON.stringify(raw).replace(/</g, '\\u003c');
  const html = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${esc(spine.title)}${spine.venue ? ' — ' + esc(spine.venue) : ''}</title>
<!-- generated by talkc from ${talkName}/talk.json; do not edit -->
<link rel="stylesheet" href="talk.css">
<style>
${trimEnd(talk.theme?.text ?? '')}
</style>
</head>
<body>
<div class="film">
<div class="stage">

${scenes.map(trimEnd).join('\n\n')}

</div>
</div>

<script type="application/json" id="text-overrides">
{"text":{},"notes":{}}
</script>
<script type="application/json" id="talk-spine">
${spineJson}
</script>
<script src="talk.js"></script>
<script src="edit.js"></script>
<script src="talk-layout.js"></script>
${scripts.map(script).join('\n')}
<script>Talk.boot();</script>
</body>
</html>
`;
  return { html, diagnostics: [] };
}

/** Compile a talk folder: write index.html, copy the engine and assets/. */
export function compileTalk(dir: string, opts: CompileOptions = {}): CompileResult {
  const talk = loadTalk(dir);
  const { html, diagnostics } = renderIndex(talk);
  if (html === null) return { ok: false, outFile: null, bytes: 0, diagnostics };
  const out = path.resolve(opts.outDir ?? path.join(dir, 'build'));
  const engine = opts.engineDir ?? defaultEngineDir();
  fs.mkdirSync(out, { recursive: true });
  const outFile = path.join(out, 'index.html');
  fs.writeFileSync(outFile, html);
  for (const f of ENGINE_FILES) fs.copyFileSync(path.join(engine, f), path.join(out, f));
  const assets = path.join(dir, 'assets');
  if (fs.existsSync(assets)) fs.cpSync(assets, path.join(out, 'assets'), { recursive: true });
  return { ok: true, outFile, bytes: Buffer.byteLength(html), diagnostics };
}
