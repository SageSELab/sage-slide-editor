// site-yaml: splice edits keep every byte they do not mean to change.
import { describe, expect, it } from 'vitest';
import { parse } from 'yaml';
import { formatScalar, isAutoGenerated, linkPaperSlides, upsertTalk, YamlEditError } from '../src/publish/site-yaml.ts';
import { PUBS, TALKS } from './site-samples.ts';

describe('upsertTalk', () => {
  const entry = { id: 'repair-issta26', title: 'Repair: How Far are We?', venue: "ISSTA'26", date: '2026-10-06', url: '/talks/repair-issta26.html' };

  it('adds a new entry at the top in the file\'s style, with a blank line after it', () => {
    const r = upsertTalk(TALKS, entry);
    expect(r.changed).toBe(true);
    expect(r.text).toBe(TALKS.replace('- id: older-talk-fse25', `- id: repair-issta26
  title: "Repair: How Far are We?"
  venue: ISSTA'26
  # Added by SAGE Talk: check the date, and add venueUrl, location and other links.
  date: '2026-10-06'
  links:
    - label: slides
      url: /talks/repair-issta26.html

- id: older-talk-fse25`));
    expect((parse(r.text) as { id: string }[])[0]).toMatchObject({ id: 'repair-issta26', title: entry.title, date: '2026-10-06', links: [{ label: 'slides', url: entry.url }] });
  });

  it('is idempotent', () => {
    const once = upsertTalk(TALKS, entry).text;
    expect(upsertTalk(once, entry)).toEqual({ text: once, changed: false });
  });

  it('adds a slides link to an existing entry, or corrects its url, touching nothing else', () => {
    const r = upsertTalk(TALKS, { ...entry, id: 'oldest-talk', url: '/talks/oldest-talk.html' });
    expect(r.text).toBe(TALKS.replace("  date: '2024-01-10'\n", "  date: '2024-01-10'\n  links:\n    - label: slides\n      url: /talks/oldest-talk.html\n"));
    const fix = upsertTalk(TALKS, { ...entry, id: 'older-talk-fse25', url: '/talks/renamed.html' });
    expect(fix.text).toBe(TALKS.replace('url: /talks/older-talk-fse25.html', 'url: /talks/renamed.html'));
  });

  it('starts an empty file', () => {
    const r = upsertTalk('# Talks\n', entry);
    expect(r.text.startsWith('# Talks\n- id: repair-issta26\n')).toBe(true);
    expect(parse(r.text)).toHaveLength(1);
  });

  it('refuses a file that does not parse or is not a list', () => {
    expect(() => upsertTalk('- id: [unclosed\n', entry)).toThrow(YamlEditError);
    expect(() => upsertTalk('talks: 1\n', entry)).toThrow(/not a block list/);
  });
});

describe('linkPaperSlides', () => {
  const url = '/talks/repair-issta26.html';
  it('adds the slides link after pdf by id, keeping quotes and the trailing spaces', () => {
    const r = linkPaperSlides(PUBS, 'pub-002', url);
    expect(r).toMatchObject({ found: true, changed: true });
    expect(r.text).toBe(PUBS.replace('url: "/documents/repair.pdf"  \n', `url: "/documents/repair.pdf"  \n    - label: "slides"\n      url: "${url}"\n`));
    expect(linkPaperSlides(r.text, 'pub-002', url)).toEqual({ text: r.text, changed: false, found: true });
  });

  it('finds the paper by title too (case-insensitive)', () => {
    expect(linkPaperSlides(PUBS, 'a paper about repair: how far are we?', url).text).toBe(linkPaperSlides(PUBS, 'pub-002', url).text);
  });

  it('adds a links block to an entry with none, before its trailing comment', () => {
    const r = linkPaperSlides(PUBS, 'pub-001', url);
    expect(r.text).toBe(PUBS.replace('  year: 2025\n', `  year: 2025\n  links:\n    - label: "slides"\n      url: "${url}"\n`));
  });

  it('corrects an existing slides url', () => {
    expect(linkPaperSlides(PUBS, 'pub-000', url).text).toBe(PUBS.replace('/talks/old-name.html', url));
  });

  it('reports a paper that is not there', () => {
    expect(linkPaperSlides(PUBS, 'pub-404', url)).toEqual({ text: PUBS, changed: false, found: false });
  });
});

describe('helpers', () => {
  it('formatScalar keeps the requested style, falling back to double quotes when plain is unsafe', () => {
    expect(formatScalar('a b', 'PLAIN')).toBe('a b');
    expect(formatScalar('a: b', 'PLAIN')).toBe('"a: b"');
    expect(formatScalar('yes', 'PLAIN')).toBe('yes');
    expect(formatScalar("it's", 'QUOTE_SINGLE')).toBe("'it''s'");
    expect(formatScalar('x"y', 'QUOTE_DOUBLE')).toBe('"x\\"y"');
  });
  it('isAutoGenerated reads the header comment', () => {
    expect(isAutoGenerated('# AUTO-GENERATED by scripts/sync-data.mjs — DO NOT EDIT.\n- id: x\n')).toBe(true);
    expect(isAutoGenerated(TALKS)).toBe(false);
  });
});
