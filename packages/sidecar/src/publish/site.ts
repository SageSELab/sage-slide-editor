// site.ts — site.stage and site.commit (PLAN 5.6; skill references/publishing.md).
//
// stage: in a site repository's working tree, copy the published file to
// public/talks/<slug>.html, add or update the talk in src/content/talks.yaml and, given a
// paper, its `slides` link in src/content/publications.yaml; then report the diff. It never
// stages, commits or pushes. A YAML file whose header says it is generated (the lab site mirrors
// the personal site's) is left alone, with a note.
// commit: only when the user clicks Commit in the app; commits exactly the paths given. There is
// no push anywhere in the sidecar: the app tells the user to push by hand.
//
// The repository path always comes from the request (the app's settings); there is no default.
import { spawn } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { RpcError, PublishErrorCode, type SiteCommitParams, type SiteCommitResult, type SiteFile, type SiteStageParams, type SiteStageResult } from '../protocol.ts';
import { isAutoGenerated, linkPaperSlides, upsertTalk, YamlEditError } from './site-yaml.ts';

export const TALKS_YAML = 'src/content/talks.yaml';
export const PUBLICATIONS_YAML = 'src/content/publications.yaml';
export const talkFile = (slug: string) => `public/talks/${slug}.html`;

const fail = (message: string, data?: unknown) => new RpcError(PublishErrorCode.SiteFailed, message, data);

/** Runs the version-control tool in `repo`; rejects with SiteFailed and its stderr. */
export function vcs(repo: string, args: string[], input?: string): Promise<string> {
  return new Promise((resolve, reject) => {
    const p = spawn('git', ['-C', repo, ...args], { env: { ...process.env, GIT_TERMINAL_PROMPT: '0', GIT_OPTIONAL_LOCKS: '0', LC_ALL: 'C' } });
    let out = '', err = '';
    p.stdout.on('data', (c: Buffer) => (out += c.toString('utf8')));
    p.stderr.on('data', (c: Buffer) => (err += c.toString('utf8')));
    p.on('error', (e) => reject(fail(`git could not run: ${e.message}`)));
    p.on('close', (code) => (code === 0 ? resolve(out) : reject(fail(`git ${args[0]} failed: ${(err || out).trim().split('\n')[0]}`, { args, stderr: err.trim() }))));
    p.stdin.end(input ?? '');
  });
}

/** The repository's top level, which `repo` must be (a subfolder or a non-repo is refused). */
export async function repoTop(repo: string): Promise<string> {
  let real: string;
  try { real = fs.realpathSync(repo); } catch { throw fail(`${repo} does not exist`); }
  if (!fs.statSync(real).isDirectory()) throw fail(`${repo} is not a folder`);
  const top = (await vcs(real, ['rev-parse', '--show-toplevel']).catch(() => { throw fail(`${repo} is not a git working tree`); })).trim();
  if (fs.realpathSync(top) !== real) throw fail(`${repo} is inside the repository ${top}; choose its top folder in Settings`);
  return real;
}

async function status(repo: string, rel: string): Promise<SiteFile['status']> {
  const s = await vcs(repo, ['status', '--porcelain', '--untracked-files=all', '--', rel]);
  const code = s.slice(0, 2);
  if (!s.trim()) return 'unchanged';
  return code === '??' || code.includes('A') ? 'added' : 'modified';
}

async function hasHead(repo: string) { return vcs(repo, ['rev-parse', '--verify', '-q', 'HEAD']).then(() => true, () => false); }

const today = () => { const d = new Date(); return `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}-${String(d.getDate()).padStart(2, '0')}`; };

export interface StageContext {
  /** The open talk's folder (the public file is build/public/<slug>.html in it). */
  talkRoot: string;
  /** talk.json's title and venue, for a new talks.yaml entry. */
  title: string;
  venue?: string;
  /** ISO date for a new entry; default today. */
  date?: string;
}

export async function stageSite(p: SiteStageParams, ctx: StageContext): Promise<SiteStageResult> {
  const src = path.join(ctx.talkRoot, 'build', 'public', `${p.slug}.html`);
  if (!fs.existsSync(src)) throw new RpcError(PublishErrorCode.NotPublished, `publish the talk as "${p.slug}" first (no ${path.relative(ctx.talkRoot, src)})`, { path: src });
  const repo = await repoTop(p.repo);
  const url = `/talks/${p.slug}.html`;
  const notes: string[] = [];

  // Plan every write first, so a YAML file that does not parse leaves the repo untouched.
  const writes: { rel: string; text: string | Buffer }[] = [];
  const html = fs.readFileSync(src);
  const dest = talkFile(p.slug);
  const destAbs = path.join(repo, dest);
  if (!fs.existsSync(destAbs) || !fs.readFileSync(destAbs).equals(html)) writes.push({ rel: dest, text: html });

  const yamlFile = (rel: string, what: string): string | null => {
    const abs = path.join(repo, rel);
    if (!fs.existsSync(abs)) { notes.push(`${rel} does not exist; ${what} left to you.`); return null; }
    const text = fs.readFileSync(abs, 'utf8');
    if (isAutoGenerated(text)) { notes.push(`${rel} is generated from another repository; ${what} comes from there.`); return null; }
    return text;
  };
  const edit = (rel: string, fn: () => { text: string; changed: boolean }) => {
    try { const r = fn(); if (r.changed) writes.push({ rel, text: r.text }); } catch (e) {
      if (e instanceof YamlEditError) throw fail(`${rel}: ${e.message}`);
      throw e;
    }
  };
  const talks = yamlFile(TALKS_YAML, 'the talk listing');
  if (talks !== null) edit(TALKS_YAML, () => upsertTalk(talks, { id: p.slug, title: ctx.title, ...(ctx.venue ? { venue: ctx.venue } : {}), date: ctx.date ?? today(), url }));
  if (p.paperEntry) {
    const pubs = yamlFile(PUBLICATIONS_YAML, 'the paper\'s slides link');
    if (pubs !== null) edit(PUBLICATIONS_YAML, () => {
      const r = linkPaperSlides(pubs, p.paperEntry!, url);
      if (!r.found) notes.push(`No entry "${p.paperEntry}" in ${PUBLICATIONS_YAML} (matched by id, then title); its slides link was not added.`);
      return r;
    });
  }

  for (const w of writes) {
    const abs = path.join(repo, w.rel);
    fs.mkdirSync(path.dirname(abs), { recursive: true });
    const tmp = `${abs}.sage-${process.pid}.tmp`;
    fs.writeFileSync(tmp, w.text);
    fs.renameSync(tmp, abs);
  }

  const rels = [dest, ...(fs.existsSync(path.join(repo, TALKS_YAML)) ? [TALKS_YAML] : []), ...(p.paperEntry && fs.existsSync(path.join(repo, PUBLICATIONS_YAML)) ? [PUBLICATIONS_YAML] : [])];
  const files: SiteFile[] = [];
  for (const rel of rels) files.push({ path: rel, status: await status(repo, rel) });
  const yamls = files.filter((f) => f.path.endsWith('.yaml') && f.status !== 'unchanged').map((f) => f.path);
  const base = (await hasHead(repo)) ? ['HEAD'] : [];
  const diff = yamls.length ? await vcs(repo, ['diff', '--no-color', '--no-ext-diff', ...base, '--', ...yamls]) : '';
  const page = files[0]!;
  const mb = (html.length / 1e6).toFixed(2);
  const head = page.status === 'unchanged' ? '' : `${dest}: ${page.status === 'added' ? 'new file' : 'replaced'}, ${mb} MB\n`;
  return { site: p.site, repo, url, files, diff: head + diff, notes };
}

export async function commitSite(p: SiteCommitParams): Promise<SiteCommitResult> {
  const repo = await repoTop(p.repo);
  for (const rel of p.paths) if (!fs.existsSync(path.join(repo, rel))) throw fail(`${rel} does not exist in ${repo}`);
  await vcs(repo, ['add', '--', ...p.paths]);
  const staged = await vcs(repo, ['diff', '--cached', '--name-only', ...((await hasHead(repo)) ? ['HEAD'] : []), '--', ...p.paths]);
  if (!staged.trim()) throw fail('nothing to commit: the files match the last commit');
  // Only these paths: anything else the user has staged stays staged.
  await vcs(repo, ['commit', '-q', '-F', '-', '--only', '--', ...p.paths], p.message.endsWith('\n') ? p.message : p.message + '\n');
  const commit = (await vcs(repo, ['rev-parse', 'HEAD'])).trim();
  const summary = (await vcs(repo, ['show', '--no-color', '--stat', '--format=%h %s', 'HEAD'])).trim();
  return { commit, summary };
}
