// site-yaml.ts — surgical edits to the Astro sites' content YAML (publishing.md: talks.yaml and
// the paper's `slides` link in publications.yaml).
//
// The `yaml` package's Document API parses the file and gives every node its source range; the
// edits are then made as text splices at those ranges, so every byte outside the edit stays as
// it was (comments, blank lines, quoting, trailing spaces). Re-stringifying the whole Document
// would be close but not exact (it trims trailing spaces, for one). New nodes copy the quoting
// style and indentation of their neighbours. Every result is re-parsed before it is returned.
import { isMap, isScalar, isSeq, parseDocument, stringify, Scalar, type Document, type Node, type YAMLMap, type YAMLSeq } from 'yaml';

export interface YamlEdit {
  text: string;
  changed: boolean;
}

export class YamlEditError extends Error {
  constructor(message: string) { super(message); this.name = 'YamlEditError'; }
}

/** A file that says it is generated (the lab site mirrors the personal site's YAML). */
export function isAutoGenerated(text: string): boolean {
  const head = text.split('\n').slice(0, 6).filter((l) => l.trimStart().startsWith('#')).join('\n');
  return /AUTO-GENERATED|DO NOT EDIT/i.test(head);
}

type Style = string | undefined;

/** A scalar written the way `style` writes it (plain only when that round-trips as a string). */
export function formatScalar(value: string, style: Style): string {
  if (style === Scalar.QUOTE_SINGLE) return `'${value.replace(/'/g, "''")}'`;
  if (style === Scalar.PLAIN) {
    const plain = stringify(value, { lineWidth: 0 }).replace(/\n$/, '');
    if (!plain.includes('\n') && !/^["'|>]/.test(plain)) return plain;
  }
  return JSON.stringify(value);
}

function parse(text: string): Document.Parsed {
  const doc = parseDocument(text);
  if (doc.errors.length) throw new YamlEditError(`does not parse: ${doc.errors[0]!.message.split('\n')[0]}`);
  return doc;
}

const lineStart = (text: string, off: number) => text.lastIndexOf('\n', off - 1) + 1;
/** Offset just past the newline ending the line that holds `off` (text length if none). */
const lineEnd = (text: string, off: number) => { const i = text.indexOf('\n', off); return i < 0 ? text.length : i + 1; };
const col = (text: string, off: number) => off - lineStart(text, off);
const splice = (text: string, at: number, end: number, insert: string) => text.slice(0, at) + insert + text.slice(end);
/** Inserting after the last line of a file without a final newline needs one first. */
const insertAt = (text: string, at: number, block: string) => (at === text.length && text.length && !text.endsWith('\n') ? text + '\n' + block : splice(text, at, at, block));

/** A node's or a value's string form (`get(k)` returns values, `get(k, true)` nodes). */
const str = (n: unknown): string | undefined => {
  const v = isScalar(n) ? n.value : n;
  return typeof v === 'string' || typeof v === 'number' ? String(v) : undefined;
};
const styleOf = (n: unknown): Style => (isScalar(n) ? (n.type === Scalar.BLOCK_FOLDED || n.type === Scalar.BLOCK_LITERAL ? Scalar.QUOTE_DOUBLE : n.type) : undefined);
const items = (seq: YAMLSeq): YAMLMap[] => seq.items.filter((i): i is YAMLMap => isMap(i));
const range = (n: Node) => n.range!;

/** Offset just past the last line of `n`'s own content (not trailing comments or blank lines). */
function contentEnd(text: string, n: Node): number {
  if (isMap(n) && n.items.length) { const last = n.items[n.items.length - 1]!; return contentEnd(text, (last.value ?? last.key) as Node); }
  if (isSeq(n) && n.items.length) return contentEnd(text, n.items[n.items.length - 1] as Node);
  const [a, b] = range(n);
  return lineEnd(text, Math.max(a, b - 1));
}

/** The first `links` entry anywhere in the document: the style new link entries copy. */
function linkStyles(root: YAMLSeq): { label: Style; url: Style } {
  for (const m of items(root)) {
    const links = m.get('links', true);
    if (isSeq(links)) for (const l of items(links)) return { label: styleOf(l.get('label', true)), url: styleOf(l.get('url', true)) };
  }
  return { label: Scalar.PLAIN, url: Scalar.PLAIN };
}

/**
 * Makes `entry`'s `links` carry {label, url}: updates the url of an existing entry with that
 * label, or adds one after the `after` label (else last), or adds a `links` block.
 */
function ensureLink(text: string, entry: YAMLMap, label: string, url: string, styles: { label: Style; url: Style }, after?: string): YamlEdit {
  const links = entry.get('links', true);
  if (isSeq(links) && links.flow) throw new YamlEditError('`links` is a flow sequence; edit it by hand');
  if (links !== undefined && links !== null && !isSeq(links) && !(isScalar(links) && links.value == null)) throw new YamlEditError('`links` is not a list');
  if (isSeq(links) && links.items.length) {
    const list = items(links);
    const have = list.find((l) => str(l.get('label')) === label);
    if (have) {
      const u = have.get('url', true);
      if (str(u) === url) return { text, changed: false };
      if (isScalar(u)) { const [a, b] = range(u); return { text: splice(text, a, b, formatScalar(url, styleOf(u))), changed: true }; }
      // A link without a url: give it one after its label.
      return { text: insertAt(text, contentEnd(text, have), `${' '.repeat(col(text, range(have)[0]))}url: ${formatScalar(url, styles.url)}\n`), changed: true };
    }
    const anchor = list.find((l) => after && str(l.get('label')) === after) ?? list[list.length - 1]!;
    const first = list[0]!;
    const keyCol = col(text, range(first)[0]);
    const dash = text.slice(lineStart(text, range(first)[0]), range(first)[0]).replace(/-\s*$/, '');
    const own = { label: styleOf(first.get('label', true)) ?? styles.label, url: styleOf(first.get('url', true)) ?? styles.url };
    const block = `${dash}- label: ${formatScalar(label, own.label)}\n${' '.repeat(keyCol)}url: ${formatScalar(url, own.url)}\n`;
    return { text: insertAt(text, contentEnd(text, anchor), block), changed: true };
  }
  // No links (or an empty `links:`): add the block after the entry's last line.
  const keyCol = col(text, range(entry)[0]);
  const ind = ' '.repeat(keyCol);
  const item = `${ind}  - label: ${formatScalar(label, styles.label)}\n${ind}    url: ${formatScalar(url, styles.url)}\n`;
  if (links !== undefined) {
    // `links:` with nothing after it: put the items under it.
    const key = entry.items.find((p) => str(p.key) === 'links')!.key as Scalar;
    return { text: insertAt(text, lineEnd(text, range(key)[1]), item), changed: true };
  }
  return { text: insertAt(text, contentEnd(text, entry), `${ind}links:\n${item}`), changed: true };
}

function rootSeq(doc: Document.Parsed, what: string): YAMLSeq | null {
  const c = doc.contents;
  if (c === null || (isScalar(c) && c.value == null)) return null;
  if (!isSeq(c) || c.flow) throw new YamlEditError(`${what} is not a block list of entries`);
  return c;
}

/** Re-parses an edit and checks it says what it should. */
function verify(edit: YamlEdit, check: (root: YAMLSeq) => boolean, what: string): YamlEdit {
  if (!edit.changed) return edit;
  const root = rootSeq(parse(edit.text), what);
  if (!root || !check(root)) throw new YamlEditError(`${what}: the edit did not produce the expected entry`);
  return edit;
}

export interface TalkEntry {
  id: string;
  title: string;
  venue?: string;
  /** ISO date (the site shows month and year). */
  date: string;
  /** Site path of the slides, /talks/<slug>.html. */
  url: string;
}

/**
 * talks.yaml: the entry with `id` gets a `slides` link to `url` (added or corrected). A missing
 * entry is added at the top (the file is newest first), in the style of the first entry.
 */
export function upsertTalk(text: string, t: TalkEntry): YamlEdit {
  const doc = parse(text);
  const root = rootSeq(doc, 'talks.yaml');
  const hasSlides = (r: YAMLSeq) => items(r).some((m) => str(m.get('id')) === t.id && isSeq(m.get('links')) && items(m.get('links') as YAMLSeq).some((l) => str(l.get('label')) === 'slides' && str(l.get('url')) === t.url));
  const styles = root ? linkStyles(root) : { label: Scalar.PLAIN, url: Scalar.PLAIN };
  const existing = root && items(root).find((m) => str(m.get('id')) === t.id);
  if (existing) return verify(ensureLink(text, existing, 'slides', t.url, styles), hasSlides, 'talks.yaml');

  const first = root ? items(root)[0] : undefined;
  const s = (k: string): Style => (first ? styleOf(first.get(k, true)) : undefined) ?? Scalar.PLAIN;
  const keyCol = first ? col(text, range(first)[0]) : 2;
  const dash = first ? text.slice(lineStart(text, range(first)[0]), range(first)[0]).replace(/-\s*$/, '') : '';
  const ind = ' '.repeat(keyCol);
  const firstLinks = first?.get('links', true);
  const linkDash = isSeq(firstLinks) && firstLinks.items.length
    ? text.slice(lineStart(text, range(firstLinks.items[0] as Node)[0]), range(firstLinks.items[0] as Node)[0]).replace(/-\s*$/, '')
    : ind + '  ';
  const lines = [
    `${dash}- id: ${formatScalar(t.id, s('id'))}`,
    `${ind}title: ${formatScalar(t.title, s('title') === Scalar.PLAIN && /[:#]/.test(t.title) ? Scalar.QUOTE_DOUBLE : s('title'))}`,
    ...(t.venue ? [`${ind}venue: ${formatScalar(t.venue, s('venue'))}`] : []),
    `${ind}# Added by SAGE Talk: check the date, and add venueUrl, location and other links.`,
    `${ind}date: ${formatScalar(t.date, first ? s('date') : Scalar.QUOTE_SINGLE)}`,
    `${ind}links:`,
    `${linkDash}- label: ${formatScalar('slides', styles.label)}`,
    `${linkDash}  url: ${formatScalar(t.url, styles.url)}`,
  ];
  let block = lines.join('\n') + '\n';
  if (!first) return verify({ text: insertAt(text, text.length, block), changed: true }, hasSlides, 'talks.yaml');
  // Entries separated by blank lines get one after the new entry too.
  const second = items(root!)[1];
  if (second && /(^|\n)[ \t]*\n/.test(text.slice(contentEnd(text, first), lineStart(text, range(second)[0])))) block += '\n';
  return verify({ text: insertAt(text, lineStart(text, range(first)[0]), block), changed: true }, hasSlides, 'talks.yaml');
}

/**
 * publications.yaml: the entry whose `id`, or else whose title (case-insensitive), is `paper`
 * gets a `slides` link to `url`, after its `pdf` link. `found: false` when there is no such entry.
 */
export function linkPaperSlides(text: string, paper: string, url: string): YamlEdit & { found: boolean } {
  const doc = parse(text);
  const root = rootSeq(doc, 'publications.yaml');
  if (!root) return { text, changed: false, found: false };
  const want = paper.trim().toLowerCase();
  const all = items(root);
  const entry = all.find((m) => str(m.get('id')) === paper.trim()) ?? all.find((m) => str(m.get('title'))?.trim().toLowerCase() === want);
  if (!entry) return { text, changed: false, found: false };
  const id = str(entry.get('id')), title = str(entry.get('title'));
  const edit = ensureLink(text, entry, 'slides', url, linkStyles(root), 'pdf');
  const ok = (r: YAMLSeq) => items(r).some((m) => str(m.get('id')) === id && str(m.get('title')) === title && isSeq(m.get('links'))
    && items(m.get('links') as YAMLSeq).some((l) => str(l.get('label')) === 'slides' && str(l.get('url')) === url));
  return { ...verify(edit, ok, 'publications.yaml'), found: true };
}
