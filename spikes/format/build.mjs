// build.mjs — throwaway compiler for the format spike: talk folder -> build/index.html.
// Usage: node spikes/format/build.mjs fixtures/issta26
// Scene files are emitted verbatim (no re-indenting: some code panes are white-space:pre
// and a line that starts inside one is content). Shape (PLAN 3/4): scenes assembled into .film/.stage, theme inlined, spine inlined as
// JSON, engine files + assets copied next to the page, lib + beats as separate inline
// classic scripts (a syntax error in one file does not blank the whole film), then boot.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const engine = path.resolve(here, '../../packages/engine/src');
const talkDir = path.resolve(process.argv[2] ?? path.resolve(here, '../../fixtures/issta26'));
const out = path.join(talkDir, 'build');
const read = (p) => fs.readFileSync(path.join(talkDir, p), 'utf8');
const spine = JSON.parse(read('talk.json'));
if (spine.format !== 'sage-talk/1') throw new Error('not a sage-talk/1 folder');

const scenes = [];
if (spine.layers) scenes.push(`<!-- ${spine.layers} -->\n` + read(spine.layers));
const motion = [];
for (const ch of spine.chapters) {
  if (ch.scene) scenes.push(`<!-- ${ch.scene} -->\n` + read(ch.scene));
  if (ch.motion) motion.push(ch.motion);
}
const script = (rel) => {
  const src = read(rel);
  new Function(src); // fail the build on a syntax error instead of shipping a blank stage
  return `<script>\n${src.replace(/\s+$/, '')}\n//# sourceURL=${rel}\n</script>`;
};
// </script> inside JSON would end the block early; escape '<' defensively.
const spineJson = JSON.stringify(spine).replace(/</g, '\\u003c');

const html = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${spine.title}${spine.venue ? ' — ' + spine.venue : ''}</title>
<!-- generated by spikes/format/build.mjs from ${path.basename(talkDir)}/talk.json; do not edit -->
<link rel="stylesheet" href="talk.css">
<style>
${read(spine.theme ?? 'theme.css').replace(/\s+$/, '')}
</style>
</head>
<body>
<div class="film">
<div class="stage">

${scenes.map((s) => s.replace(/\s+$/, '')).join('\n\n')}

</div>
</div>

<script type="application/json" id="text-overrides">
{"text":{},"notes":{}}
</script>
<script type="application/json" id="talk-spine">
${spineJson}
</script>
<script src="talk.js"></script>
<script src="edit.js"></script>
<script src="talk-layout.js"></script>
${[...(spine.lib ?? []), ...motion].map(script).join('\n')}
<script>Talk.boot();</script>
</body>
</html>
`;

fs.mkdirSync(out, { recursive: true });
fs.writeFileSync(path.join(out, 'index.html'), html);
for (const f of ['talk.js', 'talk.css', 'edit.js', 'talk-layout.js']) fs.copyFileSync(path.join(engine, f), path.join(out, f));
fs.cpSync(path.join(talkDir, 'assets'), path.join(out, 'assets'), { recursive: true });
console.log('wrote', path.relative(process.cwd(), path.join(out, 'index.html')), `(${html.length} bytes)`);
